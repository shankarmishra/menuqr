// One-time asset fetch for Phase 5 font self-hosting. Downloads the woff2 files Google Fonts
// already serves (correctly hinted, subsetted, OFL-licensed) and saves them under our own
// origin at the paths `design-system/fonts.ts#assetHref` expects, so nothing but this script
// and index.html's CDN links change — the font manifest and @font-face consumers are untouched.
//
// Run once: `node scripts/fetch-fonts.mjs`. Re-run is safe (skips files already on disk).

import { mkdir, writeFile, access } from 'node:fs/promises';
import path from 'node:path';

const OUT_DIR = path.resolve(import.meta.dirname, '../public/fonts');
const CSS_OUT = path.resolve(import.meta.dirname, '../src/design-system/fonts.generated.css');

// Mirrors the merged family set from `allFontFamilies()` in fonts.ts.
const FAMILIES = [
  { name: 'Cinzel', weights: [400, 700], subsets: ['latin'] },
  { name: 'Playfair Display', weights: [400, 600, 700], subsets: ['latin', 'latin-ext'] },
  { name: 'Plus Jakarta Sans', weights: [400, 500, 700, 800], subsets: ['latin', 'latin-ext'] },
  { name: 'Oswald', weights: [500, 700], subsets: ['latin'] },
  { name: 'Rozha One', weights: [400], subsets: ['latin', 'devanagari'] },
  { name: 'Mukta', weights: [400, 600, 700], subsets: ['latin', 'devanagari'] },
];

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

function slug(family) {
  return family.toLowerCase().replace(/\s+/g, '-');
}

function parseCss(css) {
  // Each block is preceded by a `/* <subset> */` comment naming the unicode-range that follows.
  const blocks = [];
  const re =
    /\/\* ([a-z-]+) \*\/\s*@font-face\s*{([^}]+)}/g;
  let match;
  while ((match = re.exec(css))) {
    const [, subset, body] = match;
    const weight = Number(body.match(/font-weight:\s*(\d+)/)?.[1]);
    const url = body.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/)?.[1];
    const unicodeRange = body.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();
    if (weight && url && unicodeRange) {
      blocks.push({ subset, weight, url, unicodeRange });
    }
  }
  return blocks;
}

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const cssRules = [];

  for (const family of FAMILIES) {
    const familySlug = slug(family.name);
    // One request per weight: requesting multiple weights in a single `wght@400;700` query
    // returns byte-identical files for some families (confirmed on Cinzel) — a Google Fonts API
    // quirk, not a caching issue on our end. Separate requests reliably return distinct files.
    const blocks = [];
    for (const weight of family.weights) {
      const query = `family=${encodeURIComponent(family.name)}:wght@${weight}`;
      const res = await fetch(`https://fonts.googleapis.com/css2?${query}&display=swap`, {
        headers: { 'User-Agent': UA },
      });
      if (!res.ok) {
        throw new Error(`CSS fetch failed for ${family.name} weight ${weight}: ${res.status}`);
      }
      const css = await res.text();
      blocks.push(...parseCss(css).filter((b) => family.subsets.includes(b.subset)));
    }

    for (const block of blocks) {
      const fileName = `${familySlug}-${block.weight}-${block.subset}.woff2`;
      const filePath = path.join(OUT_DIR, fileName);

      if (!(await exists(filePath))) {
        const fontRes = await fetch(block.url);
        if (!fontRes.ok) {
          throw new Error(`Font download failed for ${fileName}: ${fontRes.status}`);
        }
        const bytes = Buffer.from(await fontRes.arrayBuffer());
        await writeFile(filePath, bytes);
        console.log(`downloaded ${fileName} (${bytes.length} bytes)`);
      } else {
        console.log(`skip ${fileName} (already present)`);
      }

      cssRules.push(
        `@font-face {\n` +
          `  font-family: '${family.name}';\n` +
          `  font-style: normal;\n` +
          `  font-weight: ${block.weight};\n` +
          `  font-display: swap;\n` +
          `  src: url('/fonts/${fileName}') format('woff2');\n` +
          `  unicode-range: ${block.unicodeRange};\n` +
          `}`
      );
    }
  }

  const header =
    `/* Generated by scripts/fetch-fonts.mjs — do not hand-edit. Re-run the script to refresh. */\n\n`;
  await writeFile(CSS_OUT, header + cssRules.join('\n\n') + '\n');
  console.log(`wrote ${cssRules.length} @font-face rules to ${CSS_OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
