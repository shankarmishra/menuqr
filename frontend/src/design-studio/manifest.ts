export type AssetType = 'illustration' | 'animation';

export type AssetStatus = 
  | 'NOT_STARTED'
  | 'IN_PROGRESS'
  | 'READY_FOR_REVIEW'
  | 'APPROVED'
  | 'CHANGES_REQUESTED'
  | 'REJECTED';

export interface RevisionHistoryItem {
  id: string;
  version: string;
  timestamp: string;
  action: 'CREATED' | 'CHANGES_REQUESTED' | 'APPROVED' | 'REJECTED' | 'UPDATED';
  feedback?: string;
  author: string;
}

